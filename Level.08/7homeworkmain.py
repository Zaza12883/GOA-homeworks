#7) integer და float მონაცემთა ტიპის ცვლადებზე შეასრულეთ 20 მაგალითი ოპერატორებით: +, -, *, /, **, %

#(+)
print(10 + 5)
print(2.5 + 3.5)
print(20 + 4.5)
print(1.2 + 2.3)

#(-)
print(10 - 5)
print(8.5 - 2.5)
print(20 - 4.5)
print(9.7 - 3.2)

#(*)
print(10 * 5)
print(2.5 * 4)
print(6 * 3.5)
print(1.5 * 2.0)

#(/)
print(10 / 2)
print(7.5 / 2.5)
print(20 / 4)
print(9.0 / 2)

#(**)
print(2 ** 3)
print(3.0 ** 2)
print(5 ** 2)

#(%)
print(10 % 3)
print(7.5 % 2)